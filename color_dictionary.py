def normalize_color(variant: str) -> str:
    variant = variant.casefold().replace("ё", "е").strip()
    if " " in variant:
        return variant
    parts = variant.split("-")
    normalized_parts = [morph.parse(part)[0].normal_form.replace("ё", "е") for part in parts]
    return "-".join(normalized_parts)


COLOR_NORMALIZATION = {
    variant.casefold().replace("ё", "е"): normalize_color(variant)
    for variants in COLOR_DICTIONARY.values()
    for variant in variants
}